use super::*;

fn public(ip: &str) -> bool {
    is_public(ip.parse().unwrap())
}

#[test]
fn refuses_wordpress_ranges_and_edges() {
    for ip in [
        "0.0.0.0",
        "10.1.2.3",
        "127.0.0.1",
        "172.16.0.1",
        "172.31.255.255",
        "192.168.1.1",
        "192.0.0.8",
        "192.0.2.1",
        "192.88.99.1",
        "198.51.100.1",
        "203.0.113.1",
        "169.254.169.254",
        "100.64.0.1",
        "100.127.255.255",
        "100.100.100.200",
        "198.18.0.1",
        "198.19.255.255",
        "224.0.0.1",
        "239.1.1.1",
        "240.0.0.1",
        "255.255.255.255",
    ] {
        assert!(!public(ip), "{ip}");
    }
    for ip in [
        "1.1.1.1",
        "9.255.255.255",
        "11.0.0.1",
        "126.255.255.255",
        "128.0.0.1",
        "172.15.255.255",
        "172.32.0.1",
        "192.167.1.1",
        "192.169.1.1",
        "192.0.1.1",
        "192.0.3.1",
        "192.1.0.1",
        "192.88.98.1",
        "192.89.99.1",
        "198.51.101.1",
        "198.50.100.1",
        "203.0.114.1",
        "203.1.113.1",
        "169.253.1.1",
        "168.254.1.1",
        "100.63.255.255",
        "100.128.0.1",
        "99.64.0.1",
        "198.17.0.1",
        "198.20.0.1",
        "197.18.0.1",
        "223.255.255.255",
    ] {
        assert!(public(ip), "{ip}");
    }
}

#[test]
fn allows_global_unicast_v6_only() {
    for ip in [
        "::",
        "::1",
        "fc00::1",
        "fd00:ec2::254",
        "fe80::1",
        "ff02::1",
        "100::1",
        "2001::1",
        "2001:1ff::1",
        "2001:db8::1",
        "2002:7f00:1::1",
        "3fff::1",
        "3fff:fff::1",
        "4000::1",
        "::ffff:127.0.0.1",
        "::ffff:169.254.169.254",
        "64:ff9b::a9fe:a9fe",
        "64:ff9b::7f00:1",
        "64:ff9b:1::1",
        "::127.0.0.1",
    ] {
        assert!(!public(ip), "{ip}");
    }
    for ip in [
        "2001:200::1",
        "2001:db9::1",
        "2001:db7::1",
        "2000::1",
        "2003::1",
        "3ffe::1",
        "3fff:1000::1",
        "2606:4700::1111",
        "::ffff:1.1.1.1",
        "64:ff9b::101:101",
    ] {
        assert!(public(ip), "{ip}");
    }
}
