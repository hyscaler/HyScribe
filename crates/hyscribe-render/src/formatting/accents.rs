//! `remove_accents()`.

use std::borrow::Cow;

use icu_normalizer::ComposingNormalizerBorrowed;

/// `remove_accents( $text )` in the `en_US` locale: UTF-8 is composed (NFC)
/// and mapped by `ACCENTS`, anything else is read as ISO-8859-1.
pub fn remove_accents(text: &[u8]) -> Cow<'_, [u8]> {
    if text.is_ascii() {
        return Cow::Borrowed(text);
    }
    let Ok(utf8) = std::str::from_utf8(text) else {
        let mut out = Vec::with_capacity(text.len());
        for &b in text {
            latin1(b, &mut out);
        }
        return Cow::Owned(out);
    };
    let mut out = String::with_capacity(utf8.len());
    for c in ComposingNormalizerBorrowed::new_nfc()
        .normalize(utf8)
        .chars()
    {
        match ACCENTS.binary_search_by_key(&c, |&(from, _)| from) {
            Ok(at) => out.push_str(ACCENTS.get(at).map_or("", |&(_, to)| to)),
            Err(_) => out.push(c),
        }
    }
    Cow::Owned(out.into_bytes())
}

/// The ISO-8859-1 branch's `strtr()` and `str_replace()` of one byte.
fn latin1(b: u8, out: &mut Vec<u8>) {
    const SINGLE_IN: &[u8] = b"\x80\x83\x8a\x8e\x9a\x9e\x9f\xa2\xa5\xb5\xc0\xc1\xc2\xc3\xc4\xc5\xc7\xc8\xc9\xca\xcb\xcc\xcd\xce\xcf\xd1\xd2\xd3\xd4\xd5\xd6\xd8\xd9\xda\xdb\xdc\xdd\xe0\xe1\xe2\xe3\xe4\xe5\xe7\xe8\xe9\xea\xeb\xec\xed\xee\xef\xf1\xf2\xf3\xf4\xf5\xf6\xf8\xf9\xfa\xfb\xfc\xfd\xff";
    const SINGLE_OUT: &[u8] = b"EfSZszYcYuAAAAAACEEEEIIIINOOOOOOUUUUYaaaaaaceeeeiiiinoooooouuuuyy";
    const DOUBLE: [(u8, &[u8]); 9] = [
        (0x8c, b"OE"),
        (0x9c, b"oe"),
        (0xc6, b"AE"),
        (0xd0, b"DH"),
        (0xde, b"TH"),
        (0xdf, b"ss"),
        (0xe6, b"ae"),
        (0xf0, b"dh"),
        (0xfe, b"th"),
    ];
    if let Some(&single) = SINGLE_IN
        .iter()
        .position(|&i| i == b)
        .and_then(|at| SINGLE_OUT.get(at))
    {
        out.push(single);
    } else if let Some((_, double)) = DOUBLE.iter().find(|&&(from, _)| from == b) {
        out.extend_from_slice(double);
    } else {
        out.push(b);
    }
}

