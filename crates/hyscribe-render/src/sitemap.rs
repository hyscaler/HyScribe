//! XML sitemaps as `WP_Sitemaps_Renderer` and `WP_Sitemaps_Stylesheet`
//! print them.

use hyscribe_kses::esc_url;

/// A `<url>` of a sitemap.
pub struct Entry {
    /// `loc`.
    pub loc: Vec<u8>,
    /// `lastmod`, a `DATE_W3C` date.
    pub lastmod: Option<String>,
}

/// The sitemap index listing `locs`, with the index stylesheet of `home`.
pub fn index(home: &[u8], locs: &[Vec<u8>]) -> Vec<u8> {
    let mut xml = document(home, b"index", b"sitemapindex");
    for loc in locs {
        xml.extend_from_slice(b"<sitemap><loc>");
        xml.extend(text(&esc_url(loc)));
        xml.extend_from_slice(b"</loc></sitemap>");
    }
    xml.extend_from_slice(b"</sitemapindex>\n");
    xml
}

/// The sitemap of `entries`, with the sitemap stylesheet of `home`.
pub fn urlset(home: &[u8], entries: &[Entry]) -> Vec<u8> {
    let mut xml = document(home, b"sitemap", b"urlset");
    for entry in entries {
        xml.extend_from_slice(b"<url><loc>");
        xml.extend(text(&esc_url(&entry.loc)));
        xml.extend_from_slice(b"</loc>");
        if let Some(lastmod) = &entry.lastmod {
            xml.extend_from_slice(b"<lastmod>");
            xml.extend(text(lastmod.as_bytes()));
            xml.extend_from_slice(b"</lastmod>");
        }
        xml.extend_from_slice(b"</url>");
    }
    xml.extend_from_slice(b"</urlset>\n");
    xml
}

/// The declaration, the stylesheet instruction and the open root element,
/// as `SimpleXMLElement::asXML()` prints them.
fn document(home: &[u8], stylesheet: &[u8], root: &[u8]) -> Vec<u8> {
    let href = esc_url(&[home, b"/?sitemap-stylesheet=", stylesheet].concat());
    [
        &b"<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<?xml-stylesheet type=\"text/xsl\" href=\""
            [..],
        &href,
        b"\" ?>\n<",
        root,
        b" xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">",
    ]
    .concat()
}

/// `addChild()`'s text: entity references read, then escaped for XML.
fn text(value: &[u8]) -> Vec<u8> {
    let value = String::from_utf8_lossy(value)
        .replace("&#038;", "&")
        .replace("&#039;", "'");
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .into_bytes()
}

/// The XSL stylesheet of `kind`, `index` or `sitemap`, which names HyScribe
/// where WordPress names itself.
pub fn stylesheet(kind: &str) -> Option<&'static str> {
    match kind {
        "index" => Some(INDEX_STYLESHEET),
        "sitemap" => Some(SITEMAP_STYLESHEET),
        _ => None,
    }
}

