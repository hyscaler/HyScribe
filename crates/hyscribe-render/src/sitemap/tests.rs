use hyscribe_testkit::unhex;

use super::*;

/// The page `path` recorded from PHP WordPress by `reference/head/golden.sh`.
fn recorded(path: &str) -> String {
    let golden = include_str!("../../tests/golden/pages.tsv");
    let key = format!("{}\t", hyscribe_phpser::bin2hex(path.as_bytes()));
    let line = golden.lines().find(|line| line.starts_with(&key)).unwrap();
    String::from_utf8(unhex(line.rsplit('\t').next().unwrap())).unwrap()
}

const HOME: &[u8] = b"http://127.0.0.1:8081";

#[test]
fn the_index_matches_php_without_users() {
    let locs: Vec<Vec<u8>> = [
        "/?sitemap=posts&sitemap-subtype=post&paged=1",
        "/?sitemap=posts&sitemap-subtype=page&paged=1",
        "/?sitemap=taxonomies&sitemap-subtype=category&paged=1",
    ]
    .iter()
    .map(|path| [HOME, path.as_bytes()].concat())
    .collect();
    let php = recorded("/?sitemap=index").replace(
        "<sitemap><loc>http://127.0.0.1:8081/?sitemap=users&amp;paged=1</loc></sitemap>",
        "",
    );
    assert_eq!(String::from_utf8(index(HOME, false, &locs)).unwrap(), php);
}

#[test]
fn url_sets_match_php() {
    let page = |path: &str, lastmod: Option<&str>| Entry {
        loc: [HOME, path.as_bytes()].concat(),
        lastmod: lastmod.map(String::from),
    };
    let modified = Some("2026-10-27T08:08:15+00:00");
    let pages = [page("/", modified), page("/?page_id=2", modified)];
    assert_eq!(
        String::from_utf8(urlset(HOME, false, &pages)).unwrap(),
        recorded("/?sitemap=posts&sitemap-subtype=page&paged=1")
    );
    assert_eq!(
        String::from_utf8(urlset(HOME, false, &[page("/?cat=1", None)])).unwrap(),
        recorded("/?sitemap=taxonomies&sitemap-subtype=category&paged=1")
    );
    // Entity references read, then escaped for XML.
    assert_eq!(text(b"a&#038;b&#039;<"), b"a&amp;b'&lt;");
}

#[test]
fn stylesheets_match_php_naming_hyscribe() {
    for kind in ["index", "sitemap"] {
        let php = recorded(&format!("/?sitemap-stylesheet={kind}"))
            .replace("generated by WordPress", "generated by HyScribe");
        assert_eq!(stylesheet(kind), Some(php.as_str()));
    }
    assert_eq!(stylesheet("nope"), None);
}
