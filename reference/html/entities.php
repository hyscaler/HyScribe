// Prints crates/hyscribe-html/src/entities.rs: WordPress's table of HTML5
// named character references, sorted for binary search. Argument: a
// WordPress folder. Run through reference/html/golden.sh.

define( 'ABSPATH', rtrim( $argv[1], '/' ) . '/' );
require ABSPATH . 'wp-includes/class-wp-token-map.php';
require ABSPATH . 'wp-includes/html-api/html5-named-character-references.php';

function rust_bytes( $bytes ) {
	$out = '';
	foreach ( str_split( $bytes ) as $byte ) {
		$out .= ctype_alnum( $byte ) || ';' === $byte ? $byte : sprintf( '\\x%02x', ord( $byte ) );
	}
	return "b\"$out\"";
}

$table = $html5_named_character_references->to_array();
ksort( $table, SORT_STRING );
$longest = max( array_map( 'strlen', array_keys( $table ) ) );

echo "// SPDX-License-Identifier: AGPL-3.0-or-later\n\n";
echo "//! HTML5 named character references, as WordPress's\n";
echo "//! `html5-named-character-references.php`. Generated by\n";
echo "//! `reference/html/golden.sh`; do not edit.\n\n";
echo "/// The longest name.\n";
echo "pub(crate) const LONGEST: usize = $longest;\n\n";
echo "/// `(name, replacement)`, sorted by name.\n";
echo 'pub(crate) static ENTITIES: [(&[u8], &[u8]); ', count( $table ), "] = [\n";
foreach ( $table as $name => $replacement ) {
	echo '    (', rust_bytes( (string) $name ), ', ', rust_bytes( $replacement ), "),\n";
}
echo "];\n";
